"""Extracts the views markup, CSS and script order from ../index.html (the vanilla app) for the React shell."""
import json, re, os
here = os.path.dirname(os.path.abspath(__file__)); src = open(os.path.join(here, '..', 'index.html'), encoding='utf8').read()
css = src[src.index('<style>')+7 : src.index('</style>')]
body = src[src.index('</header>')+9 : src.index('<script src=')]
end = body.index('</section>\n</div>') + len('</section>')
views, tail = body[:end], body[end:].replace('\n</div>', '', 1)
scripts = re.findall(r'<script src="([^"]+)"></script>', src)
inline = re.findall(r'<script>(.*?)</script>', src, re.S)
out = os.path.join(here, 'src', 'legacy'); os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'legacy.css'), 'w', encoding='utf8').write(css)
open(os.path.join(out, 'markup.ts'), 'w', encoding='utf8').write('// generated by sync-legacy.py — do not edit\nexport const VIEWS = ' + json.dumps(views, ensure_ascii=False) + ';\nexport const TAIL = ' + json.dumps(tail, ensure_ascii=False) + ';\nexport const SCRIPTS: string[] = ' + json.dumps(scripts) + ';\nexport const INLINE: string[] = ' + json.dumps(inline, ensure_ascii=False) + ';\n')
print('views', len(views), 'tail', len(tail), 'scripts', len(scripts), 'inline', len(inline))
